-- STUDENT MANAGEMENT 

-- 1

CREATE VIEW STUDENT_MARKS AS
SELECT S.STUDENTID,S.STUDENTNAME,
S.COURSENAME,SUM(M.MARKS) AS TOTAL_MARKS,
ROUND(AVG(M.MARKS)) AS AVERAGE_MARKS
FROM STUDENTS S
INNER JOIN MARKS M
ON S.STUDENTID = M.STUDENTID
GROUP BY S.STUDENTID,S.STUDENTNAME;


-- 2. SHOW STUDENTS WHO HAVE PASSED
-- ALL SUBJECTS

CREATE VIEW PASS_STUDENTS AS
SELECT S.STUDENTID,S.STUDENTNAME,M.RESULT
FROM STUDENTS S
INNER JOIN MARKS M
ON S.STUDENTID = M.STUDENTID
GROUP BY S.STUDENTID, S.STUDENTNAME
HAVING RESULT='PASSED';


-- 3
CREATE VIEW HIGH_AVERAGE_STUDENTS AS
SELECT S.STUDENTID,S.STUDENTNAME,
ROUND(AVG(M.MARKS)) AS AVERAGE_MARKS
FROM STUDENTS S
INNER JOIN MARKS M
ON S.STUDENTID = M.STUDENTID
GROUP BY S.STUDENTID, S.STUDENTNAME
HAVING ROUND(AVG(M.MARKS))>80;


-- 4
CREATE VIEW COURSE_STUDENT_COUNT AS
SELECT C.COURSEID,C.COURSENAME,
COUNT(SC.STUDENTID) AS STUDENT_COUNT
FROM COURSES C
LEFT JOIN STUDENT_COURSE SC
ON C.COURSEID = SC.COURSEID
GROUP BY C.COURSEID, C.COURSENAME;


-- 5
CREATE VIEW COURSE_AVERAGE_MARKS AS
SELECT C.COURSEID,C.COURSENAME,
ROUND(AVG(M.MARKS)) AS AVERAGE_MARKS
FROM COURSES C
INNER JOIN STUDENT_COURSE SC
ON C.COURSEID = SC.COURSEID
INNER JOIN MARKS M
ON SC.STUDENTID = M.STUDENTID
GROUP BY C.COURSEID, C.COURSENAME;


-- 6. CALCULATE THE STUDENT'S GRADE USING CASE

CREATE VIEW STUDENT_GRADES AS
SELECT S.STUDENTID,S.STUDENTNAME,
ROUND(AVG(M.MARKS)) AS AVERAGE_MARKS,
CASE WHEN AVG(M.MARKS) >= 90 THEN 'A'
WHEN AVG(M.MARKS)>=75 THEN 'B'
WHEN AVG(M.MARKS)>=50 THEN 'C'
ELSE 'F'
END AS GRADE
FROM STUDENTS S
INNER JOIN MARKS M
ON S.STUDENTID = M.STUDENTID
GROUP BY S.STUDENTID, S.STUDENTNAME;






