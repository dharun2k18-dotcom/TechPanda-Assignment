-- IMPORTANT INTERVIEW QUESTIONS – SQL VIEWS

-- 1. WHAT IS A VIEW?
-- A VIEW IS A VIRTUAL TABLE THAT DISPLAYS DATA FROM ONE OR MORE TABLES USING A SQL QUERY.

-- 2. WHY DO WE USE VIEWS?
-- WE USE VIEWS TO SIMPLIFY COMPLEX QUERIES, REUSE QUERIES, AND PROVIDE DATA SECURITY BY HIDING UNNECESSARY OR SENSITIVE DATA.

-- 3. WHAT IS THE DIFFERENCE BETWEEN A TABLE AND A VIEW?
-- A TABLE STORES ACTUAL DATA PHYSICALLY IN THE DATABASE. 
-- A VIEW IS A VIRTUAL TABLE THAT DISPLAYS DATA FROM ONE OR MORE TABLES USING A SQL QUERY.

-- 4. WHAT IS THE DIFFERENCE BETWEEN A VIEW AND A STORED PROCEDURE?
-- A VIEW IS MAINLY USED TO DISPLAY OR RETRIEVE DATA AND CAN BE QUERIED LIKE A TABLE.
 -- A STORED PROCEDURE IS A STORED SET OF SQL STATEMENTS USED TO PERFORM OPERATIONS, BUSINESS LOGIC, AND OTHER TASKS.

-- 5. CAN WE INSERT DATA THROUGH A VIEW?
-- YES, DATA CAN BE INSERTED THROUGH SOME VIEWS IF THE VIEW IS UPDATABLE.

-- 6. CAN WE UPDATE DATA THROUGH A VIEW?
-- YES, DATA CAN BE UPDATED THROUGH AN UPDATABLE VIEW. 

-- 7. WHAT IS AN UPDATABLE VIEW?
-- AN UPDATABLE VIEW IS A VIEW THROUGH WHICH WE CAN PERFORM INSERT, UPDATE, OR DELETE OPERATIONS. 
-- SIMPLE VIEWS BASED ON A SINGLE TABLE ARE GENERALLY UPDATABLE.

-- 8. CAN A VIEW CONTAIN JOINS?
-- YES. A VIEW CAN BE CREATED USING JOINS BETWEEN TWO OR MORE TABLES TO DISPLAY RELATED DATA.

-- 9. CAN A VIEW CONTAIN AGGREGATE FUNCTIONS?
-- YES. A VIEW CAN CONTAIN AGGREGATE FUNCTIONS SUCH AS SUM(), AVG(), COUNT(), MAX(), AND MIN().

-- 10. CAN A VIEW CONTAIN GROUP BY?
-- YES. A VIEW CAN USE GROUP BY TO GROUP DATA AND PERFORM AGGREGATE CALCULATIONS.

-- 11. CAN A VIEW CONTAIN A SUBQUERY?
-- YES. A VIEW CAN CONTAIN A SUBQUERY TO FILTER OR CALCULATE DATA.

-- 12. CAN A VIEW CONTAIN A WINDOW FUNCTION?
-- YES A VIEW CAN CONTAIN WINDOW FUNCTIONS SUCH AS ROW_NUMBER(), RANK(), DENSE_RANK(), LEAD(), AND LAG().

-- 13. WHAT HAPPENS TO A VIEW WHEN THE UNDERLYING TABLE IS DELETED?
-- THE VIEW DEFINITION MAY REMAIN IN THE DATABASE, BUT THE VIEW CANNOT BE USED PROPERLY. 
-- QUERYING THE VIEW WILL RESULT IN AN ERROR BECAUSE THE UNDERLYING TABLE NO LONGER EXISTS.

-- 14. HOW DO YOU MODIFY AN EXISTING VIEW?
-- AN EXISTING VIEW CAN BE MODIFIED BY RECREATING OR REPLACING ITS DEFINITION USING CREATE OR REPLACE VIEW, OR BY USING ALTER VIEW.

-- 15. HOW DO YOU DELETE A VIEW?
-- A VIEW CAN BE DELETED USING THE DROP VIEW COMMAND.

-- 16. WHAT ARE THE ADVANTAGES AND DISADVANTAGES OF VIEWS?
-- ADVANTAGES:
-- (1).SIMPLIFIES COMPLEX QUERIES,(2).IMPROVES DATA SECURITY,(3).HIDES UNNECESSARY COLUMNS,
-- (4).MAKES DATA EASIER TO ACCESS.

-- DISADVANTAGES:
-- (1).COMPLEX VIEWS CAN AFFECT PERFORMANCE,(2).SOME VIEWS CANNOT BE UPDATED,
-- (3).COMPLEX OR NESTED VIEWS CAN BE DIFFICULT TO MAINTAIN.

-- 17. HOW CAN VIEWS BE USED FOR DATA SECURITY?
-- VIEWS CAN RESTRICT USERS FROM SEEING SENSITIVE DATA. 
-- FOR EXAMPLE, A VIEW CAN DISPLAY ONLY EMPLOYEE NAME AND DEPARTMENT 
-- WHILE HIDING SALARY, PASSWORD, OR OTHER CONFIDENTIAL INFORMATION. USERS CAN BE GIVEN ACCESS TO THE VIEW INSTEAD OF THE ORIGINAL TABLE.

-- 18. WHAT IS THE DIFFERENCE BETWEEN A VIEW AND A MATERIALIZED VIEW?
-- A NORMAL VIEW USUALLY STORES ONLY THE QUERY DEFINITION AND RETRIEVES THE LATEST DATA FROM THE UNDERLYING TABLES WHEN QUERIED.
-- A MATERIALIZED VIEW STORES THE RESULT OF THE QUERY PHYSICALLY. BECAUSE THE DATA IS STORED, 
-- IT MAY NEED TO BE REFRESHED TO SHOW THE LATEST CHANGES.

-- 19. CAN ONE VIEW BE CREATED USING ANOTHER VIEW?
-- YES. A NEW VIEW CAN BE CREATED BY USING AN EXISTING VIEW AS ITS DATA SOURCE. THIS IS CALLED A NESTED VIEW.

-- 20. IN A REAL-TIME PROJECT, WHEN WOULD YOU PREFER A VIEW OVER A STORED PROCEDURE?
-- I WOULD PREFER A VIEW WHEN I NEED A REUSABLE AND SIMPLIFIED WAY TO RETRIEVE DATA, HIDE SENSITIVE COLUMNS, 
-- SIMPLIFY COMPLEX JOINS, OR PROVIDE A SPECIFIC REPRESENTATION OF DATA.

-- I WOULD PREFER A STORED PROCEDURE WHEN I NEED COMPLEX BUSINESS LOGIC, MULTIPLE SQL OPERATIONS OR TRANSACTION HANDLING.








