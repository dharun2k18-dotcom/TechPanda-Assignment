CREATE VIEW CUSTOMER_ORDER_REPORT AS
SELECT C.CUSTOMERID,C.CUSTOMERNAME,
O.ORDERID,O.ORDERDATE,P.PRODUCTID,
P.PRODUCTNAME,O.QUANTITY,O.UNITPRICE,
O.QUANTITY * O.UNITPRICE AS TOTAL_AMOUNT
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
INNER JOIN PRODUCTS P
ON O.PRODUCTID = P.PRODUCTID;


-- 2. DISPLAY MONTHLY SALES SUMMARY WITH MONTH,
-- NUMBER OF ORDERS, QUANTITY SOLD, AND TOTAL REVENUE

CREATE VIEW MONTHLY_SALES_SUMMARY AS
SELECT P.PRODUCTNAME,DATE_FORMAT(O.ORDERDATE, '%Y-%M') AS SALES_MONTH,
COUNT(DISTINCT O.ORDERID) AS TOTAL_ORDERS,
SUM(OI.QUANTITY) AS QUANTITY_SOLD,
SUM(OI.QUANTITY * OI.UNITPRICE) AS TOTAL_REVENUE
FROM ORDERS O
INNER JOIN ORDER_ITEMS OI
ON O.ORDERID = OI.ORDERID
INNER JOIN PRODUCTS P
ON P.PRODUCTID=OI.PRODUCTID
GROUP BY P.PRODUCTNAME,DATE_FORMAT(O.ORDERDATE, '%Y-%M');


