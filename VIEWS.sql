-- 5. DISPLAY ORDER DETAILS ALONG WITH CUSTOMER
-- AND PRODUCT INFORMATION USING JOINS

CREATE VIEW CUSTOMER_ORDER_DETAILS AS
SELECT O.ORDERID,O.ORDERDATE,
C.CUSTOMERNAME,P.PRODUCTNAME,
O.QUANTITY,O.UNITPRICE,
O.QUANTITY*O.UNITPRICE AS TOTALAMOUNT
FROM ORDERS O
INNER JOIN CUSTOMERS C
ON O.CUSTOMERID = C.CUSTOMERID
INNER JOIN PRODUCTS P
ON O.PRODUCTID = P.PRODUCTID;


-- 6
CREATE VIEW CUSTOMER_TOTAL_SPENT AS
SELECT C.CUSTOMERID,C.CUSTOMERNAME,
SUM(O.ORDERAMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
GROUP BY C.CUSTOMERID, C.CUSTOMERNAME;


-- 7. SHOW CATEGORY-WISE TOTAL SALES

CREATE VIEW CATEGORY_TOTAL_SALES AS
SELECT P.CATEGORY,
SUM(O.QUANTITY*O.UNITPRICE) AS TOTAL_SALES
FROM PRODUCTS P
INNER JOIN ORDERS O
ON P.PRODUCTID = O.PRODUCTID
GROUP BY P.CATEGORY;


-- 8. DISPLAY TOP-SELLING PRODUCTS
-- BASED ON QUANTITY SOLD

CREATE VIEW TOP_SELLING_PRODUCTS AS
SELECT P.PRODUCTID,P.PRODUCTNAME,
SUM(O.QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM PRODUCTS P
INNER JOIN ORDERS O
ON P.PRODUCTID = O.PRODUCTID
GROUP BY P.PRODUCTID, P.PRODUCTNAME
ORDER BY TOTAL_QUANTITY_SOLD DESC;







