-- 4
CREATE VIEW CUSTOMER_TRANSACTIONS AS                           -- ASSUMED A SEPERATE TABLE FOR TRANSACTIONS
SELECT C.CUSTOMERNAME,C.CUSTOMERID,
       T.TRANSACTIONTYPE,
       T.AMOUNT,
       T.TRANSACTIONDATE
FROM CUSTOMERS C
LEFT JOIN TRANSACTIONS T
ON C.CUSTOMERID = T.CUSTOMERID;


-- 5
CREATE VIEW CURRENT_MONTH_TRANSACTIONS AS
SELECT DISTINCT C.CUSTOMERID,
       C.CUSTOMERNAME,C.ACCOUNTNUMBER
FROM CUSTOMERS C
INNER JOIN TRANSACTIONS T
ON C.CUSTOMERID = T.CUSTOMERID
WHERE MONTH(T.TRANSACTIONDATE) = MONTH(CURDATE())
AND YEAR(T.TRANSACTIONDATE) = YEAR(CURDATE());





