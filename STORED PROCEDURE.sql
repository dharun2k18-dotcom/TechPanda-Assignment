CREATE PROCEDURE TRANSFER_MONEY_TRANSACTION
(IN FROM_ACCOUNT INT,IN TO_ACCOUNT INT,
IN TRANSFER_AMOUNT DECIMAL(10,2))
BEGIN
START TRANSACTION;
IF (SELECT BALANCE FROM ACCOUNTS
WHERE ACCOUNTNUMBER = FROM_ACCOUNT) >= TRANSFER_AMOUNT
THEN
UPDATE ACCOUNTS
SET BALANCE = BALANCE - TRANSFER_AMOUNT
WHERE ACCOUNTNUMBER = FROM_ACCOUNT;
UPDATE ACCOUNTS
SET BALANCE = BALANCE + TRANSFER_AMOUNT
WHERE ACCOUNTNUMBER = TO_ACCOUNT;
COMMIT;
SELECT 'TRANSFER SUCCESSFUL' AS MESSAGE;
ELSE
ROLLBACK;
SELECT 'INSUFFICIENT BALANCE' AS MESSAGE;
END IF;
END //

