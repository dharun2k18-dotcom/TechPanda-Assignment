CREATE PROCEDURE MONTHLY_BANK_STATEMENT
(IN CUSTOMER_ID INT,IN STATEMENT_MONTH INT,IN STATEMENT_YEAR INT)
BEGIN
SELECT C.CUSTOMERID,C.CUSTOMERNAME,
c.ACCOUNTNUMBER,T.TRANSACTIONTYPE,
T.AMOUNT,T.TRANSACTIONDATE
FROM CUSTOMERS C
INNER JOIN TRANSACTIONS T
ON C.ACCOUNTNUMBER = T.ACCOUNTNUMBER
WHERE C.CUSTOMERID = CUSTOMER_ID
AND MONTH(T.TRANSACTIONDATE) = STATEMENT_MONTH
AND YEAR(T.TRANSACTIONDATE) = STATEMENT_YEAR;
END //

