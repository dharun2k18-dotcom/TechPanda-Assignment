CREATE PROCEDURE TRANSFER_MONEY
(IN FROM_ACCOUNT INT,IN TO_ACCOUNT INT,
IN TRANSFER_AMOUNT DECIMAL(10,2))
BEGIN
UPDATE ACCOUNTS
SET BALANCE = BALANCE - TRANSFER_AMOUNT
WHERE ACCOUNTNUMBER = FROM_ACCOUNT;
UPDATE ACCOUNTS
SET BALANCE = BALANCE + TRANSFER_AMOUNT
WHERE ACCOUNTNUMBER = TO_ACCOUNT;
END //

