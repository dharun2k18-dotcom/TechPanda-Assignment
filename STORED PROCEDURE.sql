DELIMITER //

CREATE PROCEDURE WITHDRAW_MONEY
(IN ACCOUNT_NO INT,IN WITHDRAW_AMOUNT DECIMAL(10,2))
BEGIN
IF (SELECT BALANCE FROM ACCOUNTS
WHERE ACCOUNTNUMBER = ACCOUNT_NO) >= WITHDRAW_AMOUNT
THEN
UPDATE ACCOUNTS
SET BALANCE =
CASE WHEN BALANCE >= WITHDRAW_AMOUNT
THEN BALANCE - WITHDRAW_AMOUNT
ELSE BALANCE
END
WHERE ACCOUNTNUMBER = ACCOUNT_NO;
INSERT INTO TRANSACTIONS
(ACCOUNTNUMBER,TRANSACTIONTYPE,
AMOUNT,TRANSACTIONDATE)
VALUES(ACCOUNT_NO,'WITHDRAW',
WITHDRAW_AMOUNT,CURDATE());
SELECT 'WITHDRAWAL SUCCESSFUL' AS MESSAGE;
ELSE
SELECT 'INSUFFICIENT BALANCE' AS MESSAGE;
END IF;
END //
