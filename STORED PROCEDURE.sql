CREATE PROCEDURE PROCESS_ORDER
(IN CUSTOMER_ID INT,IN PRODUCT_ID INT,IN ORDER_QUANTITY INT)
BEGIN
START TRANSACTION;

IF NOT EXISTS
(SELECT * FROM CUSTOMERS
WHERE CUSTOMERID = CUSTOMER_ID) THEN
SELECT 'CUSTOMER DOES NOT EXIST' AS MESSAGE;
ROLLBACK;
ELSE

IF NOT EXISTS
(SELECT * FROM PRODUCTS
WHERE PRODUCTID = PRODUCT_ID)THEN
SELECT 'PRODUCT DOES NOT EXIST' AS MESSAGE;
ROLLBACK;
ELSE

IF NOT EXISTS
(SELECT * FROM PRODUCTS
WHERE PRODUCTID = PRODUCT_ID
AND STOCK >= ORDER_QUANTITY)THEN
SELECT 'INSUFFICIENT STOCK' AS MESSAGE;
ROLLBACK;
ELSE

INSERT INTO ORDERS
(CUSTOMERID,PRODUCTID,QUANTITY,
UNITPRICE,TOTALAMOUNT,ORDERDATE,STATUS)
SELECT CUSTOMER_ID,PRODUCT_ID,ORDER_QUANTITY,
P.PRICE,ORDER_QUANTITY * P.PRICE,CURDATE(),
'COMPLETED' FROM PRODUCTS P
WHERE P.PRODUCTID = PRODUCT_ID;

UPDATE PRODUCTS
SET STOCK = STOCK - ORDER_QUANTITY
WHERE PRODUCTID = PRODUCT_ID;
COMMIT;
SELECT 'ORDER PROCESSED SUCCESSFULLY' AS MESSAGE;
END IF;
END IF;
END IF;
END //

