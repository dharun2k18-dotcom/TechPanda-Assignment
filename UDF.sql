CREATE FUNCTION CALCULATE_COMMISSION(SALES_AMOUNT DECIMAL(10,2))
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
IF SALES_AMOUNT>=100000 THEN
RETURN SALES_AMOUNT*0.10;
ELSEIF SALES_AMOUNT>=50000 THEN
RETURN SALES_AMOUNT*0.05;
ELSE
RETURN SALES_AMOUNT*0.02;
END IF;
END //
