CREATE FUNCTION CALCULATE_GRADE(MARKS INT)
RETURNS CHAR(1)
DETERMINISTIC
BEGIN
RETURN CASE
WHEN MARKS>=90 THEN 'A'
WHEN MARKS>=75 THEN 'B'
WHEN MARKS>=50 THEN 'C'
ELSE 'F'
END;
END //
