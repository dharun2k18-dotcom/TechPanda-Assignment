CREATE FUNCTION CALCULATE_DISCOUNT(PURCHASE_AMOUNT DECIMAL(10,2))
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
IF PURCHASE_AMOUNT>=10000 THEN
RETURN PURCHASE_AMOUNT*0.20;
ELSEIF PURCHASE_AMOUNT>=5000 THEN
RETURN PURCHASE_AMOUNT*0.10;
ELSE
RETURN PURCHASE_AMOUNT*0.05;
END IF;
END //
